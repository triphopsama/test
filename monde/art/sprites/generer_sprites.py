def grid(s): 
    g=[list(r) for r in s.split("\n")]
    assert all(len(r)==16 for r in g),[len(r) for r in g]
    assert len(g)==24
    return g

def step_front(g, side):
    # lift one foot: shift rows 18-22 of one leg up by 1, and bob
    g=[r[:] for r in g]
    cols = range(4,8) if side=='L' else range(8,12)
    for y in range(18,23):
        for x in cols: g[y][x]=g[y+1][x] if y<22 else '.'
    # swing arms: hand on same side goes up (sleeve), other down
    return g

def side_step(g):
    g=[r[:] for r in g]
    for i,row in enumerate(RIGHT_STEP_LEGS): g[17+i]=list(row)
    return g

def bob(g):
    return [list('.'*16)] + [r[:] for r in g[:-1]] if False else [r[:] for r in g[1:]]+[list('.'*16)]

def mirror(g): return [r[::-1] for r in g]

def add_ears(g, inner='I'):
    g=[r[:] for r in g]
    for (y,x),c in {(0,4):'O',(0,11):'O',(1,3):'O',(1,4):'I',(1,5):'O',(1,10):'O',(1,11):'I',(1,12):'O',(2,3):'O',(2,4):'I',(2,11):'I',(2,12):'O'}.items():
        g[y][x]=c
    return g

def add_tail(g, side):  # tail for up/side views
    g=[r[:] for r in g]
    if side=='up':
        pts={(15,7):'O',(15,8):'O',(16,6):'O',(16,7):'F',(16,8):'F',(16,9):'O',(17,6):'O',(17,7):'F',(17,8):'W',(17,9):'O',(18,7):'O',(18,8):'O'}
    else:  # right-facing: tail behind on the left
        pts={(14,3):'O',(15,2):'O',(15,3):'F',(15,4):'O',(16,1):'O',(16,2):'F',(16,3):'F',(16,4):'O',(17,1):'O',(17,2):'W',(17,3):'F',(17,4):'O',(18,2):'O',(18,3):'O'}
    for (y,x),c in pts.items(): g[y][x]=c
    return g

def frames(ears=False, tail=False):
    d=grid(DOWN); u=grid(UP); r=grid(RIGHT)
    if ears: d,u,r=add_ears(d),add_ears(u),add_ears(r)
    if tail: u=add_tail(u,'up'); r=add_tail(r,'side')
    rows={}
    rows['bas']=[d, bob(step_front(d,'L')), d, bob(step_front(d,'R'))]
    rows['haut']=[u, bob(step_front(u,'L')), u, bob(step_front(u,'R'))]
    rs=bob(side_step(r))
    rows['droite']=[r, rs, r, rs]
    rows['gauche']=[mirror(f) for f in rows['droite']]
    return rows

