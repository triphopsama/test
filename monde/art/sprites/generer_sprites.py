def render(name, rows, pal):
    sheet=Image.new('RGBA',(16*4,24*4),(0,0,0,0))
    for ri,k in enumerate(ORDER):
        for fi,g in enumerate(rows[k]):
            for y,row in enumerate(g):
                for x,c in enumerate(row):
                    if c!='.': sheet.putpixel((fi*16+x, ri*24+y), pal[c]+(255,))
    sheet.save(OUT+f'{name}_planche.png')
    return sheet

